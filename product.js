/* =========================
   GET CURRENT PRODUCT
========================= */

const params = new URLSearchParams(window.location.search);
const productId = params.get("id");

const product = products[productId];


/* =========================
   LOAD PRODUCT
========================= */

if (product) {

    document.title = `${product.name} — VYRA STUDIOS`;

    const mainImage =
        document.querySelector(".product-main-image img");

    const productIndex =
        document.querySelector(".product-index");

    const productName =
        document.querySelector(".product-details h1");

    const productColor =
        document.querySelector(".product-color");

    const productPrice =
        document.querySelector(".product-price");


    if (mainImage) {
        mainImage.src = product.image;
        mainImage.alt = product.name;
    }

    if (productIndex) {
        productIndex.textContent =
            `${product.id} / VYRA STUDIOS`;
    }

    if (productName) {
        productName.textContent =
            product.name;
    }

    if (productColor) {
        productColor.textContent =
            product.color;
    }

    if (productPrice) {
        productPrice.textContent =
            product.price;
    }


    /* =========================
       RELATED PRODUCTS
    ========================= */

    const relatedGrid =
        document.querySelector("#relatedGrid");

    if (relatedGrid) {

        const relatedProducts =
            Object.entries(products)

                .filter(([id, item]) => {
                    return (
                        id !== productId &&
                        item.category === product.category
                    );
                })

                .slice(0, 4);


        relatedGrid.innerHTML =
            relatedProducts.map(([id, item]) => {

                return `
                    <a
                        href="product.html?id=${id}"
                        class="related-product"
                    >

                        <div class="related-image">

                            <img
                                src="${item.image}"
                                alt="${item.name}"
                                loading="lazy"
                            >

                        </div>

                        <div class="related-info">

                            <div>

                                <h3>${item.name}</h3>

                                <p>${item.color}</p>

                            </div>

                            <strong>
                                ${item.price}
                            </strong>

                        </div>

                    </a>
                `;

            }).join("");
    }

} else {

    window.location.href = "index.html";

}


