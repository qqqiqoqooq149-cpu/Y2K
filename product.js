/* =========================================================
   PRODUCT THUMBNAILS
========================================================= */

const mainImage = document.querySelector(".product-main-image img");
const thumbs = document.querySelectorAll(".product-thumbs .thumb");

if (mainImage && thumbs.length) {

    if (thumbs[0] && product) {
        const firstThumbImage = thumbs[0].querySelector("img");

        if (firstThumbImage) {
            firstThumbImage.src = product.image;
            firstThumbImage.alt = product.name;
        }

        thumbs[0].dataset.image = product.image;
    }

    thumbs.forEach(thumb => {
        thumb.addEventListener("click", () => {
            const image = thumb.dataset.image;
            if (!image) return;

            mainImage.classList.add("changing");

            setTimeout(() => {
                mainImage.src = image;

                mainImage.onload = () => {
                    mainImage.classList.remove("changing");
                };
            }, 150);

            thumbs.forEach(item => item.classList.remove("active"));
            thumb.classList.add("active");
        });
    });
}


/* =========================================================
   ADD TO BAG — REAL CART
========================================================= */

const addToBagButton = document.querySelector(".add-to-bag");

if (addToBagButton && product && window.VyraBag) {

    addToBagButton.addEventListener("click", () => {

        const selectedSizeButton =
            document.querySelector("#productSizes button.active");

        if (!selectedSizeButton) {

            window.VyraBag.showAlert(
                "SELECT A SIZE",
                "Please select a size before adding to bag."
            );

            return;
        }

        const selectedSize =
            selectedSizeButton.textContent.trim();

        window.VyraBag.addItem({

            id: productId,

            name: product.name,

            color: product.color,

            price: product.price,

            image: product.image,

            size: selectedSize

        });

        window.VyraBag.showAlert(
            "ADDED TO BAG",
            `${product.name} — ${selectedSize}`
        );
    });
}

if (document.querySelector(".product-page")) {
    document.querySelector(".product-page").style.display = "block";
}


/* =========================================================
   PRODUCT SIZE SYSTEM
========================================================= */

const sizesContainer = document.getElementById("productSizes");

function getProductSizes(category) {

    switch (category) {

        case "caps":
            return ["ONE SIZE"];

        case "bottoms":
            return ["30", "32", "34", "36", "38"];

        case "accessories":
            return ["80 CM", "85 CM", "90 CM", "95 CM", "100 CM"];

        case "tees":
        default:
            return ["S", "M", "L", "XL", "XXL"];
    }
}


function renderProductSizes() {

    if (!sizesContainer || !product) return;

    const sizes = getProductSizes(product.category);

    sizesContainer.innerHTML = "";

    sizes.forEach(size => {

        const button = document.createElement("button");

        button.type = "button";
        button.textContent = size;

        button.addEventListener("click", () => {

            sizesContainer
                .querySelectorAll("button")
                .forEach(btn => {
                    btn.classList.remove("active");
                });

            button.classList.add("active");
        });

        sizesContainer.appendChild(button);
    });
}


renderProductSizes();